"""Write _data/cpsy1291.yml from the CPSY 1291 lecture manifest and the decks deployed
to the public course repo (serre-lab/CPSY1291-2026).

A lecture gets a slides link only when its compiled deck is present in the public repo's
slides/ directory, i.e. when deploy-to-website.sh has published it. Lectures not yet
deployed are listed by date and title only.

Usage: python scripts/sync_cpsy1291_lectures.py
"""
import json
from pathlib import Path

COURSE = Path.home() / "Work/teaching/cpsy1291/2026"
MANIFEST = COURSE / "slides/_migration_v8/manifest.json"
DEPLOYED = COURSE / "public/slides"
BASE_URL = "https://serre-lab.github.io/CPSY1291-2026/slides/"
OUT = Path(__file__).resolve().parent.parent / "_data/cpsy1291.yml"


def q(s):
    return json.dumps(s, ensure_ascii=False)  # a JSON string is a valid YAML scalar


def main():
    m = json.loads(MANIFEST.read_text())
    deployed = {p.name for p in DEPLOYED.glob("L[0-9]*.html")}
    lines = ["# Generated by scripts/sync_cpsy1291_lectures.py; do not edit by hand.", "themes:"]
    for k in sorted(m["themes"], key=int):
        lines.append(f"  - {{ n: {k}, title: {q(m['themes'][k])} }}")
    lines.append("lectures:")
    for i, lec in enumerate(m["lectures"]):
        stem = Path(lec["file"]).stem
        lines.append(f"  - n: {i}")
        lines.append(f"    date: {lec['date']}")
        lines.append(f"    theme: {lec['theme'] or 0}")
        lines.append(f"    title: {q(lec['title'])}")
        topics = lec.get("syllabus_title") or ""
        if ":" in topics and ";" not in topics.split(":", 1)[0]:
            topics = topics.split(":", 1)[1].strip()  # drop the repeated title
        elif len(topics) < len(lec["title"]) + 25:
            topics = ""  # a near-duplicate of the title adds nothing
        if topics:
            lines.append(f"    topics: {q(topics if topics.startswith("t-") else topics[0].upper() + topics[1:])}")
        if f"{stem}.html" in deployed:
            lines.append(f"    slides: {q(BASE_URL + stem + '.html')}")
            if f"{stem}-reading.html" in deployed:
                lines.append(f"    text: {q(BASE_URL + stem + '-reading.html')}")
    OUT.write_text("\n".join(lines) + "\n")
    n = sum(1 for lec in m["lectures"] if f"{Path(lec['file']).stem}.html" in deployed)
    print(f"wrote {OUT} ({n} of {len(m['lectures'])} lectures deployed)")


if __name__ == "__main__":
    main()
